const cryptoUtils = require("./cryptoUtils");
const blockchain = require("./blockchain");

/**
 * Firmware Verification Engine
 * Executes end-to-end multi-layer verification matching Section 6 & 8:
 *   A. Blockchain Metadata & Target Device Registration
 *   B. Cryptographic Hash Integrity (SHA-256 vs on-chain record) -> HASH MISMATCH
 *   C. Digital Signature Authenticity (Ed25519 vs trusted key) -> INVALID SIGNATURE
 *   D. Device Compatibility -> INCOMPATIBLE
 *   E. Approval & Revocation Status -> NOT APPROVED / FIRMWARE REVOKED
 *   F. Anti-Downgrade Version Policy (Strict integer comparison) -> DOWNGRADE ATTACK DETECTED
 */

async function verifyFirmware({
  fileBuffer,
  firmwareId,
  deviceId,
  signatureHex,
  executeOnChain = false,
  autoAdvance = true,
}) {
  const result = {
    overallStatus: "PENDING",
    passed: false,
    timestamp: new Date().toISOString(),
    computedSha256: null,
    deviceId,
    firmwareId,
    checks: [],
    rejectionReason: null,
    onChainTx: null,
  };

  // 1. Calculate SHA-256 hash of the uploaded binary
  const computedHash = cryptoUtils.calculateSha256(fileBuffer);
  result.computedSha256 = computedHash;
  const computedHashBytes32 = "0x" + computedHash;

  // 2. Query Device from Blockchain
  let device;
  try {
    const contract = blockchain.getContract();
    device = await contract.getDevice(deviceId);
    result.checks.push({
      name: "Device Registration & Status",
      passed: device.isActive,
      status: device.isActive ? "ACTIVE" : "INACTIVE",
      details: device.isActive
        ? `Device '${deviceId}' is active. Low-water version mark: ${device.minAcceptedVersion.toString()}.`
        : `Device '${deviceId}' is marked inactive.`,
    });
  } catch (error) {
    result.checks.push({
      name: "Device Registration",
      passed: false,
      status: "DEVICE_NOT_FOUND",
      details: `Device '${deviceId}' not found on blockchain registry.`,
    });
    result.overallStatus = "REJECTED";
    result.rejectionReason = `Device '${deviceId}' not registered on blockchain.`;
    return result;
  }

  // 3. Query Firmware Metadata from Blockchain
  let firmware;
  try {
    const contract = blockchain.getContract();
    firmware = await contract.getFirmware(firmwareId);
    result.checks.push({
      name: "Firmware Metadata Registration",
      passed: true,
      status: "REGISTERED",
      details: `Found on-chain release v${firmware.versionString} (Code: ${firmware.versionCode}).`,
    });
  } catch (error) {
    result.checks.push({
      name: "Firmware Registration",
      passed: false,
      status: "FIRMWARE_NOT_FOUND",
      details: `Firmware ID '${firmwareId}' not found on blockchain.`,
    });
    result.overallStatus = "REJECTED";
    result.rejectionReason = "Firmware metadata has not been registered on the blockchain.";
    return result;
  }

  // 4. CHECK B: Binary SHA-256 Hash Matching (Tampering Detection)
  const hashMatches =
    firmware.sha256Hash.toLowerCase() === computedHashBytes32.toLowerCase();

  result.checks.push({
    name: "SHA-256 Binary Integrity",
    passed: hashMatches,
    status: hashMatches ? "MATCH" : "HASH_MISMATCH",
    details: hashMatches
      ? `Binary hash matches immutable on-chain record: ${computedHash.slice(0, 16)}...`
      : `Binary tampering detected! Expected on-chain ${firmware.sha256Hash.slice(0, 16)}..., got ${computedHashBytes32.slice(0, 16)}...`,
  });

  if (!hashMatches) {
    result.overallStatus = "HASH MISMATCH";
    result.rejectionReason = "Tampered firmware detected: Computed SHA-256 hash does not match registered ledger hash.";
    return result;
  }

  // 5. CHECK C: Cryptographic Digital Signature Verification (Ed25519)
  let sigValid = false;
  let isRogueSigner = false;

  if (signatureHex) {
    const trustedPublicKey = cryptoUtils.getTrustedPublicKey();
    sigValid = cryptoUtils.verifyEd25519Signature(fileBuffer, signatureHex, trustedPublicKey);

    if (!sigValid) {
      try {
        const attackerPublicKey = cryptoUtils.getAttackerPublicKey();
        const attackerSigValid = cryptoUtils.verifyEd25519Signature(fileBuffer, signatureHex, attackerPublicKey);
        if (attackerSigValid) {
          isRogueSigner = true;
        }
      } catch (e) {
        // ignore
      }
    }
  }

  result.checks.push({
    name: "Ed25519 Digital Signature",
    passed: sigValid,
    status: sigValid ? "VALID" : isRogueSigner ? "UNTRUSTED_KEY" : "INVALID_SIGNATURE",
    details: sigValid
      ? "Cryptographic signature verified against Trusted Vendor public key."
      : isRogueSigner
      ? "Signature generated by an UNTRUSTED/ROGUE key. Rejected!"
      : "Signature verification failed: bytes do not match or signature corrupted.",
  });

  if (!sigValid) {
    result.overallStatus = "INVALID SIGNATURE";
    result.rejectionReason = isRogueSigner
      ? "Untrusted firmware signature: Not signed by authorized vendor key."
      : "Invalid digital signature: Binary or signature payload is invalid.";
    return result;
  }

  // 6. Device Compatibility
  const isCompatible = firmware.deviceModel === device.deviceModel;
  result.checks.push({
    name: "Device Compatibility",
    passed: isCompatible,
    status: isCompatible ? "COMPATIBLE" : "INCOMPATIBLE",
    details: isCompatible
      ? `Firmware target (${firmware.deviceModel}) matches device model.`
      : `Model mismatch: Firmware requires ${firmware.deviceModel}, but device is ${device.deviceModel}.`,
  });

  if (!isCompatible) {
    result.overallStatus = "REJECTED";
    result.rejectionReason = "Incompatible firmware: Target model does not match device model.";
    return result;
  }

  // 7. Revocation Check
  if (firmware.isRevoked) {
    result.checks.push({
      name: "Revocation Status",
      passed: false,
      status: "REVOKED",
      details: "This firmware release was REVOKED by security auditors due to critical vulnerabilities.",
    });
    result.overallStatus = "FIRMWARE REVOKED";
    result.rejectionReason = "Security Policy Rejection: Firmware has been explicitly revoked.";
    return result;
  }

  // 8. Approval Check
  if (!firmware.isApproved) {
    result.checks.push({
      name: "Auditor Approval",
      passed: false,
      status: "NOT_APPROVED",
      details: "Firmware is pending approval by independent Security Auditor.",
    });
    result.overallStatus = "REJECTED";
    result.rejectionReason = "Firmware has not yet been approved by an authorized Security Auditor.";
    return result;
  }

  result.checks.push({
    name: "Auditor Approval & Revocation",
    passed: true,
    status: "APPROVED",
    details: "Firmware is approved by Security Auditor and has not been revoked.",
  });

  // 9. ANTI-DOWNGRADE VERSION POLICY ENFORCEMENT
  const deviceMinVersion = Number(device.minAcceptedVersion);
  const firmwareVersionCode = Number(firmware.versionCode);
  const isVersionAllowed = firmwareVersionCode >= deviceMinVersion;

  result.checks.push({
    name: "Anti-Downgrade Version Policy",
    passed: isVersionAllowed,
    status: isVersionAllowed ? "VERSION_VALID" : "DOWNGRADE_DETECTED",
    details: isVersionAllowed
      ? `Version code ${firmwareVersionCode} meets or exceeds device minimum accepted version (${deviceMinVersion}).`
      : `DOWNGRADE ATTACK DETECTED: Attempted version (${firmwareVersionCode}) is lower than device minimum (${deviceMinVersion})!`,
  });

  if (!isVersionAllowed) {
    result.overallStatus = "DOWNGRADE ATTACK DETECTED";
    result.rejectionReason = `DOWNGRADE ATTACK PREVENTED: Firmware version code (${firmwareVersionCode}) is lower than device low-water mark (${deviceMinVersion}). Even though digital signature is valid, installation is blocked.`;
    return result;
  }

  // All 6 core checks passed!
  result.passed = true;
  result.overallStatus = "VERIFIED";

  // Execute on-chain authorization transaction if requested
  if (executeOnChain) {
    try {
      const authResult = await blockchain.authorizeUpdate(
        deviceId,
        firmwareId,
        computedHashBytes32,
        autoAdvance,
        "admin"
      );
      result.onChainTx = authResult;
      result.overallStatus = "APPROVED";
    } catch (err) {
      result.overallStatus = "ON_CHAIN_REVERT";
      result.rejectionReason = `On-chain authorization reverted: ${err.message}`;
    }
  }

  return result;
}

module.exports = {
  verifyFirmware,
};
